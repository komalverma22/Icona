/**
 * Discover set — practical icons most libraries skip: developer workflow
 * (regex, variables, breakpoints, webhooks), data visualisation, accessibility,
 * layout / wayfinding, UI states, touch gestures and productivity.
 * Same design language as `iconData.ts`: 24px grid, 1.5px round strokes, fill
 * variants via silhouette + mask knock-outs.
 *
 * Icons with dashed strokes stay static: the generic "draw" animation drives
 * the stroke dash itself and would erase the dash pattern.
 */

type Extra = Omit<Partial<IconNode>, "type" | "id">;

const p = (id: string, d: string, extra: Extra = {}): IconNode => ({ id, type: "path", d, ...extra }) as IconNode;
const c = (id: string, cx: number, cy: number, r: number, extra: Extra = {}): IconNode =>
  ({ id, type: "circle", cx, cy, r, ...extra }) as IconNode;

